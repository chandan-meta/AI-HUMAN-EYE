using System;
using UnityEngine;

namespace HumanEye
{
    public enum StepKind
    {
        Shot,     // key = camera shot, value = blend seconds, async = don't wait for the blend
        Say,      // key = dialogue cue id; waits for audio completion (or an explicit Read & Continue)
        Do,       // key = whitelisted stage action, arg/value = parameters, async = run alongside next steps
        Await,    // key = learner action (scan, inside, brighter, dimmer, near, distant, continue)
        Explore,  // runs the chapter's explore entries until every part's explanation has finished
        Hold,     // value = seconds a critical close-up stays on screen
        Offer,    // key = SupplementalAdaptive quick check at an approved checkpoint (help after misses; no Skip)
        Free      // key = hands-on experiment (brightness, photoreceptors); ends when the learner taps Continue
    }

    [Serializable]
    public class Step
    {
        public StepKind kind;
        public string key, arg;
        public float value;
        public bool async;
        [TextArea] public string note;
    }

    [Serializable]
    public class ExploreEntry
    {
        public string partId, label;
        public Step[] steps;
    }

    /// One storyboard chapter (source IDs Scene02–Scene11). Generated by Tools > Human Eye > Build Module
    /// from HumanEyeContent.cs; the runner interprets the steps in order.
    [CreateAssetMenu(menuName = "Human Eye/Chapter Definition")]
    public class ChapterDefinition : ScriptableObject
    {
        public string id, title;
        [TextArea] public string checkpoint;
        public string[] topics;
        public Step[] steps;
        public ExploreEntry[] explore;
    }
}
